    def test_cpp_and_bazel_rewrites_match_autoroller(self) -> None:
        raw_cpp = (
            '#include "include/core/SkCanvas.h"\n'
            '#include "local_keep.h" // NO_G3_REWRITE\n'
            '#include "third_party/already_prefixed.h"\n'
            "#include <hb.h>\n"
        )
        out_cpp = ar.rewrite_cpp_content(raw_cpp)
        self.assertIn('#include "third_party/skia/HEAD/include/core/SkCanvas.h"\n', out_cpp)
        self.assertIn('#include "local_keep.h"  // NO_G3_REWRITE\n', out_cpp)
        self.assertIn('#include "third_party/already_prefixed.h"\n', out_cpp)
        self.assertIn('#include "third_party/harfbuzz/src/hb.h"\n', out_cpp)

        raw_bzl = (
            'load("//bazel:skia_rules.bzl", "skia_cc_library")\n'
            'skia_cc_library(\n'
            '    name = "t",\n'
            '    deps = ["//:core", "//modules/skunicode:skunicode_core"],\n'
            ')\n'
        )
        out_bzl = ar.rewrite_bazel_content(raw_bzl, "modules/skparagraph/BUILD.bazel")
        self.assertTrue(out_bzl.startswith("# THIS FILE IS AUTOGENERATED"))
        self.assertIn("//third_party/skia/HEAD/bazel:skia_rules.bzl", out_bzl)
        self.assertIn("//third_party/skia/HEAD:core", out_bzl)
        self.assertIn("//third_party/skia/HEAD/modules/skunicode:skunicode_core", out_bzl)

