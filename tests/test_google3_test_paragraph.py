    def test_bep_comparison_flips_and_attestation_integrity(self) -> None:
        targets = ["//a:pass_to_fail", "//b:fail_to_pass", "//c:both_fail", "//d:steady_pass"]

        def _make_bep(statuses: dict[str, str], inv_id: str) -> list[str]:
            evs = [
                json.dumps(
                    {
                        "id": {"started": {}},
                        "started": {"uuid": inv_id, "startTimeMillis": "1000"},
                    }
                )
            ]
            for lbl, st in statuses.items():
                evs.append(
                    json.dumps(
                        {
                            "id": {"testSummary": {"label": lbl}},
                            "testSummary": {"overallStatus": st, "totalRunDurationMillis": "250"},
                        }
                    )
                )
            evs.append(
                json.dumps(
                    {
                        "id": {"buildMetrics": {}},
                        "buildMetrics": {"actionSummary": {"actionsExecuted": "42"}},
                    }
                )
            )
            evs.append(
                json.dumps(
                    {
                        "id": {"buildFinished": {}},
                        "finished": {
                            "finishTimeMillis": "5000",
                            "exitCode": {"code": 3, "name": "TESTS_FAILED"},
                        },
                    }
                )
            )
            return evs

        with tempfile.TemporaryDirectory() as td:
            out = pathlib.Path(td)
            for name, tree_sha, rw_cnt, st_map in [
                (
                    "base",
                    "1111222233334444",
                    0,
                    {
                        "//a:pass_to_fail": "PASSED",
                        "//b:fail_to_pass": "FAILED",
                        "//c:both_fail": "FAILED",
                        "//d:steady_pass": "PASSED",
                    },
                ),
                (
                    "cand",
                    "aaaabbbbccccdddd",
                    2,
                    {
                        "//a:pass_to_fail": "FAILED",
                        "//b:fail_to_pass": "PASSED",
                        "//c:both_fail": "FAILED",
                        "//d:steady_pass": "PASSED",
                    },
                ),
            ]:
                leg = out / name
                leg.mkdir()
                (leg / "targets.txt").write_text("\n".join(targets) + "\n", encoding="utf-8")
                bep_p = leg / "bep.json"
                bep_p.write_text(
                    "\n".join(_make_bep(st_map, f"uuid-{name}")) + "\n", encoding="utf-8"
                )
                sm = pg3.parse_bep_file(bep_p, expected_targets=targets)
                (leg / "summary.json").write_text(json.dumps(sm), encoding="utf-8")
                (leg / "attestation.json").write_text(
                    json.dumps(
                        {
                            "ref_spec": "G3_HEAD" if name == "base" else "WORKTREE",
                            "citc_client": "skia_g3_ab",
                            "citc_base_cl": 1008000000,
                            "citc_pre_dirty_files": [],
                            "citc_restored_clean": True,
                            "g3_skia_revision": "e87e231404cc95f114dfc58a33b7f573af84edac",
                            "source_tree_sha256": tree_sha,
                            "rewritten_file_count": rw_cnt,
                            "tier": "fast",
                            "blaze_rc": 3,
                        }
                    ),
                    encoding="utf-8",
                )

            runs = [
                ("base", pg3.collect_run_data(str(out / "base"), None)),
                ("cand", pg3.collect_run_data(str(out / "cand"), None)),
            ]
            md = pg3.format_comparison_markdown(runs)
            self.assertIn("`VALID (", md)
            self.assertIn("`//a:pass_to_fail` (`PASSED` -> `FAILED`)", md)
            self.assertIn("`//b:fail_to_pass` (`FAILED` -> `PASSED`)", md)
            self.assertIn("`//c:both_fail` (`FAILED` -> `FAILED`)", md)

            # Identical tree hash between base and cand must trigger WARNING / INVALID
            runs[1][1]["attestation"]["source_tree_sha256"] = "1111222233334444"
            md_bad = pg3.format_comparison_markdown(runs)
            self.assertIn("`WARNING / INVALID`", md_bad)

