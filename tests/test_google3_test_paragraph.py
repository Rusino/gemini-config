    def test_sync_skia_tree_to_g3_writes_build_and_deletes(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            tmp = pathlib.Path(td)
            skia_root = tmp / "skia"
            g3_root = tmp / "g3"
            (skia_root / "modules/skparagraph/src").mkdir(parents=True)
            (g3_root / "third_party/skia/HEAD/modules/skparagraph/src").mkdir(parents=True)

            (skia_root / "modules/skparagraph/src/Run.cpp").write_text(
                '#include "modules/skparagraph/src/Run.h"\n', encoding="utf-8"
            )
            (skia_root / "modules/skparagraph/src/BUILD.bazel").write_text(
                'load("//bazel:skia_rules.bzl", "skia_filegroup")\n'
                'skia_filegroup(name = "srcs", srcs = ["Run.cpp"])\n',
                encoding="utf-8",
            )
            obsolete_g3 = g3_root / "third_party/skia/HEAD/modules/skparagraph/src/Dead.cpp"
            obsolete_g3.write_text("// old\n", encoding="utf-8")

            res = ar.sync_skia_tree_to_g3(
                skia_root,
                g3_root,
                changed_or_added=[
                    "modules/skparagraph/src/Run.cpp",
                    "modules/skparagraph/src/BUILD.bazel",
                ],
                deleted=["modules/skparagraph/src/Dead.cpp"],
            )
            g3_run = g3_root / "third_party/skia/HEAD/modules/skparagraph/src/Run.cpp"
            g3_build = g3_root / "third_party/skia/HEAD/modules/skparagraph/src/BUILD"
            self.assertIn(
                '#include "third_party/skia/HEAD/modules/skparagraph/src/Run.h"',
                g3_run.read_text(encoding="utf-8"),
            )
            self.assertTrue(g3_build.exists())
            self.assertFalse(obsolete_g3.exists())
            self.assertEqual(
                res["deleted"], ["third_party/skia/HEAD/modules/skparagraph/src/Dead.cpp"]
            )

